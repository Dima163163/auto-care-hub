import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { evaluateMigrationChecksumManifest, loadPublishedMigrationManifest } from './check-migration-checksum.mjs'
import { extractRequiredGateIds, validateReleasePromotion } from './check-release-promotion.mjs'
import { buildMigrationInventory } from './check-migration-inventory.mjs'
import { decryptReleaseEvidence, encryptReleaseEvidence } from './release-evidence-encryption.mjs'
import { getGitProvenance, sha256File } from './release-provenance.mjs'

const projectRoot = resolve(fileURLToPath(new URL('..', import.meta.url)))
const SHA256_PATTERN = /^[a-f0-9]{64}$/
const GIT_SHA_PATTERN = /^[a-f0-9]{40}$/

function requireEnv(name) {
    const value = process.env[name]
    if (!value) throw new Error(`${name} is required.`)
    return value
}

function parseJson(value, name) {
    try {
        return JSON.parse(value)
    } catch {
        throw new Error(`${name} must contain valid JSON.`)
    }
}

function workflowCoordinates(workflowRef) {
    const separator = workflowRef.lastIndexOf('@')
    if (separator < 0) throw new Error('GitHub workflow ref is malformed.')
    return {
        workflowPath: workflowRef.slice(0, separator).replace(`${process.env.GITHUB_REPOSITORY}/`, ''),
        workflowRef: workflowRef.slice(separator + 1).replace(/^refs\/heads\//, ''),
    }
}

function assertTrustedQualityRun(run, repository, releaseSha) {
    if (!run || run.repository !== repository
        || run.workflowPath !== '.github/workflows/quality.yml'
        || run.workflowRef !== 'dev'
        || run.event !== 'push'
        || run.headBranch !== 'dev'
        || run.headSha !== releaseSha
        || run.status !== 'completed'
        || run.conclusion !== 'success'
        || !Number.isSafeInteger(Number(run.runId))
        || typeof run.runUrl !== 'string'
        || !run.runUrl.startsWith('https://github.com/')) {
        throw new Error('The referenced quality run must be a successful push workflow on dev for the exact release SHA.')
    }
}

async function main() {
    const releaseSha = requireEnv('RELEASE_SHA')
    const repository = requireEnv('GITHUB_REPOSITORY')
    const workflow = workflowCoordinates(requireEnv('GITHUB_WORKFLOW_REF'))
    const runId = requireEnv('GITHUB_RUN_ID')
    const runUrl = requireEnv('GITHUB_RUN_URL')
    const runnerTemp = requireEnv('RUNNER_TEMP')
    const sourceRoot = resolve(requireEnv('RELEASE_SOURCE_DIR'))
    const artifactPath = requireEnv('RELEASE_ARTIFACT_PATH')
    const migrationManifestPath = resolve(runnerTemp, 'published-migration-manifest.json')
    const qualityRun = parseJson(await readFile(resolve(requireEnv('QUALITY_RUN_FILE')), 'utf8'), 'QUALITY_RUN_FILE')

    if (!GIT_SHA_PATTERN.test(releaseSha)) {
        throw new Error('Release SHA must be a full immutable commit SHA.')
    }
    if (workflow.workflowPath !== '.github/workflows/release-evidence.yml' || workflow.workflowRef !== 'main'
        || process.env.GITHUB_REF !== 'refs/heads/main' || process.env.GITHUB_EVENT_NAME !== 'workflow_dispatch') {
        throw new Error('Release evidence must be generated by the protected workflow_dispatch policy on main.')
    }
    assertTrustedQualityRun(qualityRun, repository, releaseSha)

    const sourceProvenance = parseJson(await readFile(resolve(requireEnv('SOURCE_PROVENANCE_FILE')), 'utf8'), 'SOURCE_PROVENANCE_FILE')
    if (sourceProvenance.commitSha !== releaseSha || sourceProvenance.clean !== true || !SHA256_PATTERN.test(sourceProvenance.manifestSha256 ?? '')) {
        throw new Error('The source checkout must be clean and match the release SHA before building.')
    }

    const encryptedEvidence = parseJson(requireEnv('RELEASE_EVIDENCE_ENCRYPTED'), 'RELEASE_EVIDENCE_ENCRYPTED')
    const suppliedEvidence = parseJson(decryptReleaseEvidence(encryptedEvidence), 'decrypted release evidence')
    const submittedManifest = parseJson(requireEnv('MIGRATION_MANIFEST_JSON'), 'MIGRATION_MANIFEST_JSON')
    const allowedManifestFields = new Set(['schemaVersion', 'inventoryChecksum', 'migrations', 'generatedAt', 'count', 'checksum'])
    if (Object.keys(submittedManifest).some((field) => !allowedManifestFields.has(field))) {
        throw new Error('Migration manifest may contain only its schema, inventory checksum, migration list and generated inventory metadata.')
    }
    const submittedManifestPath = resolve(runnerTemp, 'submitted-migration-manifest.json')
    await writeFile(submittedManifestPath, JSON.stringify(submittedManifest), { mode: 0o600 })
    const loadedManifest = await loadPublishedMigrationManifest(submittedManifestPath)
    const allowedMigrationFields = new Set(['fileName', 'sha256', 'sourceSha256'])
    if (loadedManifest.migrations.some((entry) => Object.keys(entry).some((field) => !allowedMigrationFields.has(field)))) {
        throw new Error('Migration manifest entries may contain only filenames and SHA-256 hashes.')
    }
    const manifest = {
        schemaVersion: 1,
        inventoryChecksum: loadedManifest.inventoryChecksum,
        migrations: loadedManifest.migrations.map((migration) => ({
            fileName: migration.fileName,
            sha256: migration.sha256 ?? migration.sourceSha256,
        })),
    }
    await writeFile(migrationManifestPath, `${JSON.stringify(manifest, null, 2)}\n`, { mode: 0o600 })

    const migration = await evaluateMigrationChecksumManifest({
        migrationDirectory: resolve(sourceRoot, 'server/src/database/migrations'),
        manifestPath: migrationManifestPath,
    })
    if (!migration.pass) throw new Error('The applied migration manifest does not match immutable published migration sources.')

    const inventory = await buildMigrationInventory(resolve(sourceRoot, 'server/src/database/migrations'))
    const config = {
        NEXT_PUBLIC_API_MODE: requireEnv('NEXT_PUBLIC_API_MODE'),
        NEXT_PUBLIC_API_BASE_URL: requireEnv('NEXT_PUBLIC_API_BASE_URL'),
        NEXT_PUBLIC_API_ORIGIN: requireEnv('NEXT_PUBLIC_API_ORIGIN'),
        NEXT_PUBLIC_SITE_URL: requireEnv('NEXT_PUBLIC_SITE_URL'),
    }
    const configFingerprint = createHash('sha256').update(JSON.stringify(config)).digest('hex')
    const artifactSha256 = await sha256File(artifactPath)
    const now = new Date().toISOString()
    const sourceRun = {
        runId: Number(runId),
        repository,
        workflowPath: workflow.workflowPath,
        workflowRef: workflow.workflowRef,
        event: process.env.GITHUB_EVENT_NAME,
        headBranch: process.env.GITHUB_REF_NAME,
        headSha: process.env.GITHUB_SHA,
        releaseSha,
        status: 'completed',
        conclusion: 'success',
        runUrl,
    }

    const evidence = {
        ...suppliedEvidence,
        schemaVersion: 1,
        environment: 'production',
        releaseSha,
        artifactSha256,
        sourceTree: {
            clean: sourceProvenance.clean,
            dirtyManifestSha256: sourceProvenance.manifestSha256,
        },
        configFingerprint,
        executedAt: now,
        generatedAt: now,
        signature: {
            algorithm: 'GitHub Artifact Attestation (Sigstore/SLSA)',
            signer: `${repository}/${workflow.workflowPath}`,
            value: `attested-by-github-actions-${runId}-${releaseSha}`,
            verificationUri: runUrl,
        },
        sourceRun,
        qualityRun,
        migration: {
            ...(suppliedEvidence.migration ?? {}),
            inventoryChecksum: inventory.checksum,
            manifestSha256: await sha256File(migrationManifestPath),
        },
    }

    const scopeSource = await readFile(resolve(projectRoot, 'docs/operations/PILOT_SCOPE_FREEZE.md'), 'utf8')
    const checks = validateReleasePromotion(evidence, {
        expectedReleaseSha: releaseSha,
        currentProvenance: sourceProvenance,
        expectedArtifactSha256: artifactSha256,
        requiredGateIds: extractRequiredGateIds(scopeSource),
    })
    const blocked = checks.filter((check) => check.status === 'blocked')
    if (blocked.length > 0) {
        throw new Error(`Release evidence does not pass the existing promotion contract (${blocked.length} blocked check(s)); no artifacts were published.`)
    }

    const encryptedEvidenceOutput = encryptReleaseEvidence(JSON.stringify(evidence))
    await writeFile(resolve(runnerTemp, 'release-evidence.enc.json'), `${JSON.stringify(encryptedEvidenceOutput, null, 2)}\n`, { mode: 0o600 })
    console.log(`Prepared encrypted release evidence for ${releaseSha}; ${evidence.gates.length} required-gate records are present.`)
}

main().catch((error) => {
    console.error(`[prepare-release-evidence] ${error instanceof Error ? error.message : String(error)}`)
    process.exitCode = 1
})
